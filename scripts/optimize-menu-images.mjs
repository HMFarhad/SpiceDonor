import sharp from 'sharp';
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const input = new URL('../src/assets/images/Items/', import.meta.url);
const output = new URL('../src/assets/images/menu-optimized/', import.meta.url);
await mkdir(output, { recursive: true });
const manifest = {};
const photos = (await readdir(input)).filter(name => /\.jpe?g$/i.test(name)).sort()
  .map(name => ({ name, source: join(fileURLToPath(input), name), url: `assets/images/Items/${name}` }));
photos.push({ name: 'Fish n Chips.png', source: join(fileURLToPath(input), '../Fish n Chips.png'), url: 'assets/images/Fish n Chips.png' });
for (const { name, source, url } of photos) {
  const id = createHash('sha256').update(name).digest('hex').slice(0, 12);
  const variants = {};
  const sourceInfo = await stat(source);
  for (const width of [480, 960, 1440]) {
    const filename = `${id}-${width}.webp`;
    const destination = join(fileURLToPath(output), filename);
    const existing = await stat(destination).catch(() => null);
    const info = existing && existing.mtimeMs >= sourceInfo.mtimeMs && !process.argv.includes('--force')
      ? await sharp(destination).metadata()
      : await sharp(source).rotate().trim({ threshold: 20 }).resize({ width, withoutEnlargement: true })
        .webp({ quality: 78 }).toFile(destination);
    // A smaller source is never enlarged; srcset describes the actual output width.
    variants[info.width] = `assets/images/menu-optimized/${filename}`;
  }
  manifest[url] = variants;
}
await writeFile(new URL('../src/app/shared/menu-image-manifest.ts', import.meta.url),
  '// Generated by npm run images:optimize. Original workbook image URLs remain supported.\n'
  + 'export const menuImageManifest: Record<string, Record<number, string>> = '
  + JSON.stringify(manifest, null, 2) + ';\n');
console.log(`Optimized ${Object.keys(manifest).length} photos at 480, 960 and 1440px.`);
